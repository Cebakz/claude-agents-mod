# Installs (or updates) "claude agents mod" on this machine (Windows):
#   1. copies the program to ~/.claude/agentes-mod/program;
#   2. creates the claude-agents-mod.cmd shortcut in ~/.local/bin, pointing to that copy;
#   3. in PowerShell, "claude agents mod" opens the panel (every other "claude" command is unchanged);
#   4. with -StatusLine, also installs the status-line mod (context bar and plan usage).
# The program installs its libraries (pywinpty and pyte) itself the first time it opens.
#
# Usage, from inside the cloned folder:  powershell -ExecutionPolicy Bypass -File install.ps1 [-StatusLine]
# To update later:                      git pull, then run the same command again.
param([switch]$StatusLine)

$ErrorActionPreference = "Stop"
$here = $PSScriptRoot

$real = Get-Command claude.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $real) { throw "claude.exe not found in PATH: install Claude Code first" }
if (-not (Get-Command py -ErrorAction SilentlyContinue)) { throw "py (Python launcher) not found: install Python 3.11" }

# 1. The program.
$dest = Join-Path $env:USERPROFILE ".claude\agentes-mod\program"
New-Item -ItemType Directory -Force $dest | Out-Null
Copy-Item (Join-Path $here "agents_mod.py"), (Join-Path $here "agents_mod.cmd") $dest -Force

# 2. The shortcut.
$bin = Join-Path $env:USERPROFILE ".local\bin"
New-Item -ItemType Directory -Force $bin | Out-Null
@"
@echo off
rem Opens the agents panel (claude agents mod). Generated by install.ps1.
call "$dest\agents_mod.cmd" %*
"@ | Set-Content -Encoding ascii (Join-Path $bin "claude-agents-mod.cmd")

# 3. The "claude" function in the PowerShell profile (Windows PowerShell and, if present, PowerShell 7).
$function = @'

# "claude agents mod" opens the agents panel; any other "claude ..." goes straight to claude.exe.
function claude {
    $exe = '__EXE__'
    if (-not (Test-Path $exe)) { $exe = (Get-Command claude.exe -CommandType Application | Select-Object -First 1).Source }
    if ($args.Count -ge 2 -and $args[0] -eq "agents" -and $args[1] -eq "mod") {
        & (Join-Path $env:USERPROFILE ".local\bin\claude-agents-mod.cmd") @($args | Select-Object -Skip 2)
        return
    }
    if ($MyInvocation.ExpectingInput) { $input | & $exe @args } else { & $exe @args }
}
'@.Replace("__EXE__", $real.Source.Replace("'", "''"))
$docs = [Environment]::GetFolderPath("MyDocuments")
if (-not $docs) { $docs = Join-Path $env:USERPROFILE "Documents" }
$profiles = @(Join-Path $docs "WindowsPowerShell\Microsoft.PowerShell_profile.ps1")
if (Get-Command pwsh -ErrorAction SilentlyContinue) { $profiles += Join-Path $docs "PowerShell\Microsoft.PowerShell_profile.ps1" }
foreach ($profilePath in $profiles) {
    New-Item -ItemType Directory -Force (Split-Path $profilePath) | Out-Null
    if (-not (Test-Path $profilePath)) { New-Item -ItemType File $profilePath | Out-Null }
    if (-not (Select-String -Path $profilePath -Pattern 'claude-agents-mod.cmd' -Quiet)) {
        $function | Add-Content -Encoding utf8 $profilePath
    }
}
# Without this the profile does not load on a default Windows (scripts blocked). Current user only.
if ((Get-ExecutionPolicy -Scope CurrentUser) -eq "Undefined" -and
    (Get-ExecutionPolicy -Scope LocalMachine) -in @("Undefined", "Restricted", "AllSigned")) {
    Set-ExecutionPolicy -Scope CurrentUser RemoteSigned -Force
}

# 4. Optional: the status-line mod, which saves /context and plan usage for the panel to show.
if ($StatusLine) {
    $mod = Join-Path $env:USERPROFILE ".claude\mods\status-line"
    New-Item -ItemType Directory -Force $mod | Out-Null
    Copy-Item (Join-Path $here "status-line\*") $mod -Recurse -Force
    # Claude Code loads the mod through the CLAUDE_CODE_PLUGIN_DIRS variable in the user's settings.json.
    $settings = Join-Path $env:USERPROFILE ".claude\settings.json"
    $json = if (Test-Path $settings) { Get-Content $settings -Raw -Encoding utf8 | ConvertFrom-Json } else { [pscustomobject]@{} }
    if (-not $json.env) { $json | Add-Member -NotePropertyName env -NotePropertyValue ([pscustomobject]@{}) }
    $dirs = [string]$json.env.CLAUDE_CODE_PLUGIN_DIRS
    if (($dirs -split ';') -notcontains $mod) {
        if (Test-Path $settings) { Copy-Item $settings "$settings.bak-agents-mod" -Force }   # backup before editing
        $new = (@($dirs -split ';' | Where-Object { $_ }) + $mod) -join ';'
        if ($json.env.PSObject.Properties.Name -contains "CLAUDE_CODE_PLUGIN_DIRS") { $json.env.CLAUDE_CODE_PLUGIN_DIRS = $new }
        else { $json.env | Add-Member -NotePropertyName CLAUDE_CODE_PLUGIN_DIRS -NotePropertyValue $new }
        [IO.File]::WriteAllText($settings, ($json | ConvertTo-Json -Depth 32), (New-Object Text.UTF8Encoding $false))
        Write-Host "status-line enabled in settings.json (previous version saved as settings.json.bak-agents-mod)."
    }
}

Write-Host "Done. Open a new PowerShell and run: claude agents mod"
